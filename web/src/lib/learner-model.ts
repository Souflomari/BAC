/**
 * learner-model.ts — the read layer: raw persisted facts → what the
 * dashboard is allowed to say (LEARNER-MODEL-SPEC.md).
 *
 * Every function here is PURE: no fetch, no Supabase, no `fs`, no
 * `Date.now()` read internally (a `now: Date` is always a PARAMETER, never
 * read from the ambient clock) — so every rule in the spec is testable on a
 * plain fixture, exactly as §8 requires ("La classification A/C/U est du
 * code pur (lecture) → tests unitaires sur table de cas, pas dom-truth").
 * The three input shapes below mirror the draft schemas byte-for-byte
 * (`backend/supabase/migrations/048_user_events_and_notion_progress.sql`,
 * `draft-049_user_notion_misconception_states.sql`) — camelCased, nothing
 * renamed beyond that. Nothing here writes anything; the write path (RPCs,
 * edge functions) stays untouched and stays the only place clearing facts
 * get decided (ADR 0013: "le chemin d'écriture ne classifie pas" — and
 * symmetrically, the read layer never re-derives what the write path
 * already decided, e.g. `cleared_at`).
 *
 * NO %, no streak, no XP, no "maîtrisé" anywhere below — the honest-state
 * vocabulary ban (LEARNER-MODEL-SPEC §8) applies to this module's own
 * output as much as to any rendered string.
 */

