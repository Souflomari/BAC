// Generates migration 018 — quiz items for the 32 SMA-specific (sma_*) skills
// that have v2 lessons but ZERO items. Pattern-authored from the lesson
// checkpoints. ~6-8 items per chapter, mix of MCQ and numeric.
//
// Run:
//   dart backend/seed/json_encode_items_sma.dart

import 'dart:convert';
import 'dart:io';

void main(List<String> args) {
  final out = StringBuffer();
  out.writeln('-- ============================================================');
  out.writeln('-- Migration 018: Items for SMA-specific (sma_*) skills.');
  out.writeln('-- Auto-generated by backend/seed/json_encode_items_sma.dart.');
  out.writeln('-- Targets the 32 SMA chapters with v2 lessons, which had ZERO');
  out.writeln('-- items prior to this migration (009/010 predate the sma_*');
  out.writeln('-- skill layer added in 012).');
  out.writeln('-- ============================================================');
  out.writeln();
  out.writeln('BEGIN;');
  out.writeln();

  var seq = 1;
  for (final entry in _items.entries) {
    final skillUuid = entry.key;
    final list = entry.value;
    out.writeln('-- ===== $skillUuid (${list.length} items) =====');
    for (final it in list) {
      final id = _itemUuid(seq++);
      final question = jsonEncode(it.question).replaceAll("'", "''");
      final explanation = jsonEncode(it.explanation).replaceAll("'", "''");
      final tagsArr = '{${it.tags.map((t) => '"$t"').join(",")}}';
      out.writeln(
          "INSERT INTO public.items (id, skill_id, item_type, difficulty_level, content_language, question, explanation, tags)");
      out.writeln(
          "VALUES ('$id', '$skillUuid', '${it.type}', ${it.difficulty}, 'fr', '$question'::jsonb, '$explanation'::jsonb, '$tagsArr')");
      out.writeln('ON CONFLICT (id) DO NOTHING;');
    }
    out.writeln();
  }

  out.writeln('COMMIT;');

  final output = args.isNotEmpty
      ? args[0]
      : 'backend/supabase/migrations/018_items_sma_specific.sql';
  File(output).writeAsStringSync(out.toString());
  stdout.writeln('Wrote $output (${seq - 1} items across ${_items.length} skills).');
}

String _itemUuid(int n) {
  // Series 44444444-aaaa-0000-0000-0000000NNNNN to avoid collision with 009/010.
  final hex = n.toRadixString(16).padLeft(12, '0');
  return '44444444-aaaa-0000-0000-$hex';
}

class _Item {
  final String type; // 'mcq' or 'numeric'
  final int difficulty;
  final Map<String, dynamic> question;
  final Map<String, dynamic> explanation;
  final List<String> tags;
  _Item({
    required this.type,
    required this.difficulty,
    required this.question,
    required this.explanation,
    required this.tags,
  });
}

_Item _mcq({
  required String stem,
  required List<String> choices,
  required int correct,
  required String explanation,
  int difficulty = 2,
  List<String>? tags,
}) =>
    _Item(
      type: 'mcq',
      difficulty: difficulty,
      question: {
        'stem': stem,
        'choices': choices,
        'correct_index': correct,
        'latex': true,
      },
      explanation: {
        'text_fr': explanation,
        'steps': const <String>[],
      },
      tags: tags ?? const ['bac_style'],
    );

_Item _num({
  required String stem,
  required num correct,
  num tolerance = 0,
  required String explanation,
  List<String>? steps,
  int difficulty = 2,
  List<String>? tags,
}) =>
    _Item(
      type: 'numeric',
      difficulty: difficulty,
      question: {
        'stem': stem,
        'correct_value': correct,
        'tolerance': tolerance,
        'latex': true,
      },
      explanation: {
        'text_fr': explanation,
        'steps': steps ?? const <String>[],
      },
      tags: tags ?? const ['bac_style'],
    );

